CREATE TABLE ticket_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ticket_id BIGINT NOT NULL, 
	actor_id BIGINT NOT NULL, 
	event_type VARCHAR(24) NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	old_status VARCHAR(16), 
	new_status VARCHAR(16) NOT NULL, 
	old_assignee_id BIGINT, 
	new_assignee_id BIGINT, 
	version INTEGER NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT uq_ticket_event_version UNIQUE (ticket_id, version), 
	CONSTRAINT ck_event_type CHECK (event_type IN ('created','taken','status_changed','refused','reassigned','reopened')), 
	FOREIGN KEY(ticket_id) REFERENCES tickets (id), 
	FOREIGN KEY(actor_id) REFERENCES users (id), 
	FOREIGN KEY(old_assignee_id) REFERENCES users (id), 
	FOREIGN KEY(new_assignee_id) REFERENCES users (id)
)


-- statement --
CREATE INDEX ix_ticket_event_history ON ticket_events (ticket_id, created_at, id)
