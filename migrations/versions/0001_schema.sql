CREATE TABLE ticket_drafts (
	id UUID NOT NULL, 
	user_id BIGINT NOT NULL, 
	step VARCHAR(16) DEFAULT 'description' NOT NULL, 
	description TEXT, 
	priority VARCHAR(16), 
	request_id VARCHAR(64), 
	tenant_id VARCHAR(64), 
	version INTEGER DEFAULT '1' NOT NULL, 
	prompt_message_id BIGINT, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_draft_step CHECK (step IN ('description','priority','request_id','tenant_id','confirm')), 
	CONSTRAINT ck_draft_version CHECK (version >= 1), 
	UNIQUE (user_id), 
	FOREIGN KEY(user_id) REFERENCES users (id)
)


-- statement --
CREATE INDEX ix_draft_updated ON ticket_drafts (updated_at)
