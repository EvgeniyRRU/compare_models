CREATE TABLE tickets (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	author_id BIGINT NOT NULL, 
	assignee_id BIGINT, 
	description TEXT NOT NULL, 
	priority VARCHAR(16) NOT NULL, 
	request_id VARCHAR(64) NOT NULL, 
	tenant_id VARCHAR(64), 
	status VARCHAR(16) DEFAULT 'new' NOT NULL, 
	version INTEGER DEFAULT '1' NOT NULL, 
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	taken_at TIMESTAMP WITH TIME ZONE, 
	closed_at TIMESTAMP WITH TIME ZONE, 
	next_reminder_at TIMESTAMP WITH TIME ZONE, 
	message_id BIGINT, 
	post_synced_version INTEGER DEFAULT '0' NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_ticket_status CHECK (status IN ('new','in_progress','waiting_info','resolved','rejected','duplicate')), 
	CONSTRAINT ck_ticket_priority CHECK (priority IN ('critical','high','medium','low')), 
	CONSTRAINT ck_ticket_description CHECK (length(btrim(description)) > 0 AND length(description) <= 3000), 
	CONSTRAINT ck_ticket_request CHECK (length(btrim(request_id)) > 0 AND length(request_id) <= 64), 
	CONSTRAINT ck_ticket_tenant CHECK (tenant_id IS NULL OR (length(btrim(tenant_id)) > 0 AND length(tenant_id) <= 64)), 
	CONSTRAINT ck_ticket_version CHECK (version >= 1 AND post_synced_version >= 0 AND post_synced_version <= version), 
	CONSTRAINT ck_ticket_assignment CHECK ((status != 'new' OR (assignee_id IS NULL AND taken_at IS NULL)) AND (status NOT IN ('in_progress','waiting_info') OR (assignee_id IS NOT NULL AND taken_at IS NOT NULL))), 
	CONSTRAINT ck_ticket_closed CHECK ((status IN ('resolved','rejected','duplicate')) = (closed_at IS NOT NULL)), 
	CONSTRAINT ck_ticket_reminder CHECK ((status = 'new') = (next_reminder_at IS NOT NULL)), 
	FOREIGN KEY(author_id) REFERENCES users (id), 
	FOREIGN KEY(assignee_id) REFERENCES users (id)
)


-- statement --
CREATE INDEX ix_ticket_assignee_date ON tickets (assignee_id, created_at, id)
-- statement --
CREATE INDEX ix_ticket_due ON tickets (next_reminder_at) WHERE status = 'new'
-- statement --
CREATE INDEX ix_ticket_author_date ON tickets (author_id, created_at, id)
-- statement --
CREATE INDEX ix_ticket_filter_date ON tickets (status, priority, created_at, id)
-- statement --
CREATE INDEX ix_ticket_unsynced ON tickets (id) WHERE message_id IS NULL OR post_synced_version < version
