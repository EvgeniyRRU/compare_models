CREATE FUNCTION support_set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$
-- statement --
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION support_set_updated_at()
-- statement --
CREATE TRIGGER tickets_updated_at BEFORE UPDATE ON tickets FOR EACH ROW EXECUTE FUNCTION support_set_updated_at()
-- statement --
CREATE TRIGGER ticket_drafts_updated_at BEFORE UPDATE ON ticket_drafts FOR EACH ROW EXECUTE FUNCTION support_set_updated_at()